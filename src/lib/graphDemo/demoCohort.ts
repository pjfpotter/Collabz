// THE MADE-UP PEOPLE IN THE GRAPH DEMO (graph-demo, group 1).
//
// NOTHING IN THIS FILE IS REAL. These 40 people are invented and written
// straight into the source, the same way the landing-page demo does it
// (src/components/landing/demoCast.ts). The demo page never reads the
// database, so it can't show a real student, and it never needs the dev-only
// pretend cohort (PRETEND_COHORT), so it works on the live site.
//
// WHY THEIR NAMES HAVE NO "PRETEND" IN THEM: the pretend cohort names people
// "The Pretend Mad Inventor 07" so developers can tell them from real users.
// Here every person has an alias built exactly the way a real one is, "The" +
// their Vibe word + their Energy word, so the graph reads like the product.
//
// WHY TAG IDS AND NOT TAG NAMES: ids never change (rule B2), and the score
// formula works on ids. Every id below comes from prisma/seed-data.ts, and
// tests/unit/graphDemoCohort.test.ts checks that they all still exist.
//
// WHY THE NAMED CONSTANTS BELOW: a typo in a plain string would only be found
// by a test. A typo in `VIBE.feral` is a red underline in your editor.

// Which course a person is on. The ids match seedCourses in prisma/seed-data.ts.
export type DemoCourseId = "software" | "business";

// One invented person.
export type DemoPerson = {
  // Only used to tell the demo people apart, e.g. "demo-07". It is not a
  // database id and never matches one.
  id: string;
  // "The Feral Gremlin". Written out so a beginner can read the cohort
  // straight off this file; a test checks it follows the real alias rule.
  alias: string;
  // An id from the shared set in public/silhouettes, e.g. "silhouette-07".
  silhouette: string;
  course: DemoCourseId;
  // The same five categories the score formula reads (see PersonTags in
  // src/lib/matching/score.ts). Skills and Interests are left out on purpose:
  // they are never part of a score (rule B5).
  heroStory: string[];
  energy: string[];
  vibeDiagnosis: string[];
  qualities: string[];
  seeking: string[];
};

